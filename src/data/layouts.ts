/** Rotates a layout 90 degrees clockwise. */
export function rotateCW(rows: string[]): string[] {
  const h = rows.length;
  const w = rows[0].length;
  const out: string[] = [];
  for (let y = 0; y < w; y++) {
    let line = '';
    for (let x = 0; x < h; x++) line += rows[h - 1 - x][y];
    out.push(line);
  }
  return out;
}

export function rotateTimes(rows: string[], n: number): string[] {
  let r = rows;
  for (let i = 0; i < ((n % 4) + 4) % 4; i++) r = rotateCW(r);
  return r;
}

/** Plain layouts for special 1x1 rooms. */
export function openLayout(decor: 'entrance' | 'blood' | 'fairy' | 'puzzle'): string[] {
  if (decor === 'fairy') {
    return ['........', '........', '..#..#..', '........', '........', '..#..#..', '........', '........'];
  }
  if (decor === 'entrance') {
    return ['#......#', '........', '........', '........', '........', '........', '........', '#......#'];
  }
  return Array.from({ length: CELL }, () => '.'.repeat(CELL));
}
